-- Intentionally nullable during migration: old habitat categories cannot be
-- automatically translated into detailed environmental descriptors.
CREATE MATERIALIZED VIEW public.view_all_organisms_info AS
	SELECT
	    o.id,
	    o.individual_id,
	
	    s.id AS species_id,
	    s.name AS species_name,
	
	    sa.id AS sampling_site_id,
	    sa.name AS sampling_site_name,
	
	    sa.habitat_code AS habitat_name,
	    
	    sa.is_contact_zone,
	    
	    hs.name AS habitat_structure_name,
	
	    l.id AS location_id,
	    l.name AS location_name,
	
	    c.name AS country_name,
	
	    tr.id AS trait_id,
	    tr.name AS trait_name,
	
	    p.id AS property_id,
	    p.name AS property_name,
	    p.template_column_name,
	
	    op.value
	
	FROM public.organism AS o
	
	JOIN public.species AS s
	    ON s.id = o.species_id
	
	JOIN public.sampling_area AS sa
	    ON sa.id = o.sampling_site_id

	LEFT JOIN public.habitat_structure AS hs
	    ON hs.id = sa.habitat_structure_id
	
	
	JOIN public.location AS l
	    ON l.id = sa.location_id
	
	JOIN public.country AS c
	    ON c.id = l.country_id
	
	CROSS JOIN public.property AS p
	
	JOIN public.trait AS tr
	    ON tr.id = p.trait_id
	
	LEFT JOIN public.organism_property AS op
	    ON op.organism_id = o.id
	   AND op.property_id = p.id
	
	ORDER BY
	    o.id,
	    p.id
WITH NO DATA;

CREATE MATERIALIZED VIEW public.view_home_sampling_area_counts AS
 SELECT sa.id,
    sa.name,
    sa.latitude,
    sa.longitude,
    sa.habitat_code AS habitat_name,
    sa.is_contact_zone,
    hs.name AS habitat_structure_name,
    count(1) AS number_individuals
   FROM public.organism o
     JOIN public.sampling_area sa ON sa.id = o.sampling_site_id
     LEFT JOIN public.habitat_structure hs ON hs.id = sa.habitat_structure_id
  GROUP BY sa.id, sa.name, sa.latitude, sa.longitude, sa.habitat_code, sa.is_contact_zone, hs.name
  WITH NO DATA;

CREATE MATERIALIZED VIEW public.view_home_traits_data_counts AS
SELECT
    trait_id,
    trait_name,
    COUNT(DISTINCT id) AS number_entries
FROM public.view_all_organisms_info
WHERE value IS NOT NULL
GROUP BY trait_id, trait_name
ORDER BY trait_name
WITH NO DATA;
COMMIT;

